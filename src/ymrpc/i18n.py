"""Минималистичная локализация без внешних зависимостей."""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any

logger = logging.getLogger(__name__)

LANGUAGES = {"ru": "Русский", "en": "English"}
_current = "ru"


@dataclass(frozen=True)
class Message:
    key: str
    values: dict[str, Any]

    def render(self) -> str:
        return t(self.key, **self.values)


def set_language(language: str) -> None:
    global _current
    _current = language if language in LANGUAGES else "ru"


def current_language() -> str:
    return _current


def t(key: str, **values: Any) -> str:
    table = _EN if _current == "en" else _RU
    text = table.get(key) or _RU.get(key) or _EN.get(key) or key
    if values:
        try:
            return text.format(**values)
        except (KeyError, ValueError, IndexError):
            return text
    return text


def source_label(source_id: str, source_name: str = "") -> str:
    """Человекочитаемое имя приложения-источника."""
    payload = source_id or source_name
    folded = payload.casefold()
    known = (
        ("yandex", "Яндекс Музыка"),
        ("spotify", "Spotify"),
        ("msedge", "Microsoft Edge"),
        ("chrome", "Google Chrome"),
        ("firefox", "Mozilla Firefox"),
        ("opera", "Opera"),
        ("brave", "Brave"),
        ("vivaldi", "Vivaldi"),
        ("vlc", "VLC"),
        ("aimp", "AIMP"),
        ("foobar", "foobar2000"),
        ("apple", "Apple Music"),
        ("itunes", "iTunes"),
        ("musicbee", "MusicBee"),
        ("tidal", "TIDAL"),
        ("deezer", "Deezer"),
        ("soundcloud", "SoundCloud"),
        ("youtube", "YouTube"),
        ("telegram", "Telegram"),
    )
    for needle, label in known:
        if needle in folded:
            return label
    if source_name:
        return source_name
    if "!" in payload:
        payload = payload.split("!", 1)[1]
    if "." in payload:
        payload = payload.rsplit(".", 1)[-1]
    return payload.replace("_", " ").strip() or t("source.unknown")


